"""Deterministic WiX MSI definition generator for Windows engine installers.

The generator is pure standard library so the ``.wxs`` definition can be built
and verified on any host; only the final ``wix build`` step requires Windows
(or a CI runner) with the WiX toolset installed.

Identifiers are derived with UUIDv5 from the product name and payload paths so
the same release always produces byte-identical definitions, and upgrade and
component identities stay stable across versions.
"""

from __future__ import annotations

import json
import tarfile
import uuid
import zipfile
from pathlib import Path
from xml.sax.saxutils import quoteattr

UPGRADE_NAMESPACE = "torviello-installer-upgrade"
COMPONENT_NAMESPACE = "torviello-installer-component"
MANUFACTURER = "Torviello"
INSTALL_DIRECTORY = "Torviello Engine"

WIX_HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by torviello-engine/packaging/wix_installer.py; do not edit. -->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
"""


class InstallerError(Exception):
    """Raised when an installer definition cannot be generated."""


def upgrade_code(product: str) -> str:
    """Return the stable upgrade code for a product name."""
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"{UPGRADE_NAMESPACE}:{product}")).upper()


def component_guid(product: str, member: str) -> str:
    """Return the stable component GUID for one payload member."""
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"{COMPONENT_NAMESPACE}:{product}:{member}")).upper()


def component_id(member: str) -> str:
    """Return a deterministic WiX-safe identifier for a payload member."""
    cleaned = "".join(char if char.isalnum() else "_" for char in member)
    return f"C_{cleaned}"


def file_id(member: str) -> str:
    return f"F_{component_id(member)[2:]}"


def load_release_manifest(manifest_path: Path) -> dict:
    manifest_path = Path(manifest_path).resolve()
    if not manifest_path.is_file():
        raise InstallerError(f"manifest does not exist: {manifest_path}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    for field in ("product", "version", "target", "files"):
        if field not in manifest:
            raise InstallerError(f"release manifest is missing {field!r}")
    if not manifest["files"]:
        raise InstallerError("release manifest lists no files")
    return manifest


def extract_payload(archive_path: Path, payload_root: Path) -> list[str]:
    """Extract a release archive into the payload directory and return members."""
    archive_path = Path(archive_path).resolve()
    if not archive_path.is_file():
        raise InstallerError(f"artifact does not exist: {archive_path}")
    payload_root.mkdir(parents=True, exist_ok=True)
    if archive_path.name.endswith(".zip"):
        with zipfile.ZipFile(archive_path) as archive:
            archive.extractall(payload_root)  # noqa: S202 (zip, not tar)
            members = sorted(archive.namelist())
    elif archive_path.name.endswith((".tar.gz", ".tgz")):
        with tarfile.open(archive_path) as archive:
            archive.extractall(payload_root, filter="data")
            members = sorted(member.name for member in archive.getmembers())
    else:
        raise InstallerError(f"unsupported archive format: {archive_path.name}")
    return members


def generate(manifest: dict, members: list[str]) -> str:
    """Render the WiX definition for one release manifest and payload."""
    product = str(manifest["product"])
    version = str(manifest["version"])
    payload_members = set(members)
    for entry in manifest["files"]:
        if entry["path"] not in payload_members:
            raise InstallerError(f"payload is missing manifest file: {entry['path']}")
    lines = [
        WIX_HEADER.rstrip(),
        (
            f'<Package Name={quoteattr(f"{MANUFACTURER} Engine")} '
            f'Manufacturer={quoteattr(MANUFACTURER)} '
            f'Version={quoteattr(version)} '
            f'UpgradeCode={quoteattr(upgrade_code(product))} '
            'Scope="perMachine" Compressed="yes" Language="1033" Codepage="65001">'
        ),
        '  <MajorUpgrade '
        'DowngradeErrorMessage="A newer version of [ProductName] is already installed." />',
        '  <MediaTemplate EmbedCab="yes" />',
        '  <StandardDirectory Id="ProgramFiles64Folder">',
        f'    <Directory Id="INSTALLFOLDER" Name={quoteattr(INSTALL_DIRECTORY)} />',
        "  </StandardDirectory>",
        '  <ComponentGroup Id="EngineFiles" Directory="INSTALLFOLDER">',
    ]
    for member in members:
        guid = component_guid(product, member)
        identifier = component_id(member)
        lines.extend(
            [
                f"    <Component Id={quoteattr(identifier)} Guid={quoteattr(guid)}>",
                f"      <File Id={quoteattr(file_id(member))} "
                f'Source={quoteattr(f"payload/{member}")} KeyPath="yes" />',
                "    </Component>",
            ]
        )
    lines.extend(
        [
            '    <Component Id="C_PathEnvironment" Guid='
            + quoteattr(component_guid(product, "environment/PATH"))
            + ">",
            '      <Environment Id="ENV_PATH" Name="PATH" Value="[INSTALLFOLDER]bin" '
            'Part="last" Action="set" System="yes" />',
            "    </Component>",
            "  </ComponentGroup>",
            '  <Feature Id="Main" Title="Torviello Engine" Level="1">',
            '    <ComponentGroupRef Id="EngineFiles" />',
            "  </Feature>",
            "</Package>",
            "</Wix>",
        ]
    )
    return "\n".join(lines) + "\n"


def installer_document(manifest_path: str, archive_path: str, out: str) -> dict:
    """Extract the payload, render the definition, and write both under out."""
    output = Path(out)
    manifest = load_release_manifest(Path(manifest_path))
    members = extract_payload(Path(archive_path), output / "payload")
    name = f"{manifest['product']}-{manifest['version']}-{manifest['target']}.wxs"
    definition_path = output / name
    definition_path.write_text(generate(manifest, members), encoding="utf-8")
    return {
        "definition": str(definition_path),
        "payload": str(output / "payload"),
        "members": len(members),
        "upgrade_code": upgrade_code(str(manifest["product"])),
    }
